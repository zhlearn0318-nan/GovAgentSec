import fs from 'node:fs';
import path from 'node:path';
import {homedir} from 'node:os';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
const repo=fileURLToPath(new URL('../',import.meta.url));
const profile=homedir();
const config=JSON.parse(fs.readFileSync(path.join(profile,'.openclaw/openclaw.json'),'utf8'));
const source=path.join(repo,'modules/grid-native/skills/grid-anomaly-diagnosis');
const target=path.join(config.agents.defaults.workspace,'skills/grid-anomaly-diagnosis');
if(fs.existsSync(path.join(target,'SKILL.md')))throw Error('Grid skill already installed; use prepare_native_grid_config.mjs to configure without overwriting the published version');
const policy=config.security.installPolicy.exec;
const request={protocolVersion:1,openclawVersion:'2026.7.1-2',targetType:'skill',targetName:'grid-anomaly-diagnosis',sourcePathKind:'directory',sourcePath:source};
const result=spawnSync(policy.command,policy.args,{input:JSON.stringify(request),encoding:'utf8',windowsHide:true,timeout:180000,env:{...process.env,...policy.env}});
if(result.error||result.status!==0)throw Error('Native baseline admission process failed');
const response=JSON.parse(result.stdout);if(response.decision!=='allow')throw Error('Native baseline admission did not allow: '+JSON.stringify(response));
const content=fs.readFileSync(path.join(source,'SKILL.md'),'utf8');
fs.mkdirSync(target,{recursive:true});fs.writeFileSync(path.join(target,'SKILL.md'),content);
const evidence={installed:true,scope:'openclaw-grid-demo',version:'1.0.0',source:'operator-authored-baseline',artifact_hash:createHash('sha256').update(content).digest('hex'),checked_at:new Date().toISOString(),response};
fs.writeFileSync(path.join(target,'admission.json'),JSON.stringify(evidence,null,2));
const validation=path.join(repo,'local-validation/native-grid');fs.mkdirSync(validation,{recursive:true});fs.writeFileSync(path.join(validation,'baseline-admission.json'),JSON.stringify(evidence,null,2));
await import('./prepare_native_grid_config.mjs');
console.log(JSON.stringify({admitted:true,installed:true,version:'1.0.0',target,hash:evidence.artifact_hash}));
