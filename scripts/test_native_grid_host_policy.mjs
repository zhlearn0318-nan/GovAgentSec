import fs from 'node:fs';
import path from 'node:path';
import {homedir} from 'node:os';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const host=process.env.OPENCLAW_HOST_ROOT||path.join(process.env.APPDATA||path.join(homedir(),'AppData','Roaming'),'npm/node_modules/openclaw');
assert.equal(JSON.parse(fs.readFileSync(path.join(host,'package.json'),'utf8')).version,'2026.7.1-2');
const {r:resolveEffectiveToolPolicy,t:filterToolsByPolicy}=await import(pathToFileURL(path.join(host,'dist/agent-tools.policy-YD9HuYgO.js')));
const {h:profilePolicy,c:merge}=await import(pathToFileURL(path.join(host,'dist/tool-policy-BHUGxE3p.js')));
const names=['gov_read_document','gov_analyze_grid'];
const config={agents:{defaults:{workspace:process.cwd()},list:[{id:'main',tools:{allow:names,alsoAllow:[]}}]},tools:{profile:'coding',alsoAllow:names}};
const before=resolveEffectiveToolPolicy({config,agentId:'main'});
assert.deepEqual(before.profileAlsoAllow,[]);
assert.deepEqual(filterToolsByPolicy(names.map(name=>({name})),merge(profilePolicy(before.profile),before.profileAlsoAllow)),[]);
delete config.agents.list[0].tools.alsoAllow;
const after=resolveEffectiveToolPolicy({config,agentId:'main'});
assert.deepEqual(after.profileAlsoAllow,names);
const profile=filterToolsByPolicy([...names,'exec'].map(name=>({name})),merge(profilePolicy(after.profile),after.profileAlsoAllow));
const final=filterToolsByPolicy(profile,after.agentPolicy);
assert.deepEqual(final.map(t=>t.name),names);
console.log(JSON.stringify({passed:true,host:'2026.7.1-2',before:[],after:final.map(t=>t.name),unrelatedExecStillDenied:true}));
